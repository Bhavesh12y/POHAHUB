export function gamesForMode(mode) {
  return GAMES.filter((g) => !g.hidden && g.modes.includes(mode));
}

export function getGame(id) {
  return GAMES.find((g) => g.id === id) || null;
}

export function isSoloGame(id) {
  return Boolean(getGame(id)?.modes.includes('solo'));
}

export const SOLO_PLAY_PATHS = GAMES.filter((g) => g.modes.includes('solo')).map((g) => g.playPath);
